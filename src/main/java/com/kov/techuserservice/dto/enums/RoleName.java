package com.kov.techuserservice.dto.enums;

/**
 * Перечисление уровней доступа пользователя в системе.
 * Определяет полномочия и область видимости данных для каждого типа аккаунта.
 */
public enum RoleName {

    /**
     * Обычный пользователь.
     * Доступ: просмотр каталога, создание и управление собственными заказами, оформление адресов, просмотр профиля.
     */
    USER,

    /**
     * Менеджер.
     * Доступ: всё, что доступно USER, плюс управление заказами других пользователей, просмотр статистики, работа с inventory.
     */
    MANAGER,

    /**
     * Администратор.
     * Доступ: полный контроль над системой — управление пользователями, ролями, товарами, заказами, конфигурацией.
     */
    ADMIN
}
